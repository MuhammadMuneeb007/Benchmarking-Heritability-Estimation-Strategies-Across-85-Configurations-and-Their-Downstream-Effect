def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "mode",
        nargs="?",
        default="real",
        choices=["real", "simulated"],
        help="real or simulated; default=real",
    )

    args = parser.parse_args()
    mode = args.mode

    try:
        root = resolve_root(mode)
    except FileNotFoundError as exc:
        sys.exit(f"ERROR: {exc}")

    if mode == "real":
        expected = expected_real_files(root)
        files = [p for p in expected if p.exists()]
    else:
        files = discover_sim_files(root)

    if not files:
        sys.exit(
            f"ERROR: No Results_Liability.csv files found for {mode} under {root}"
        )

    raw = load_all(files, root, mode)

    if raw.empty:
        sys.exit("ERROR: No usable rows were loaded.")

    long_df = make_long(raw)

    if mode == "real":
        phenotype_order = [
            p for p in PHENOTYPES
            if p in set(long_df["Phenotype"])
        ]
    else:
        phenotype_order = sorted(
            [
                p for p in long_df["Phenotype"].dropna().astype(str).unique()
                if is_sim_id(p)
            ],
            key=sim_number,
        )

    if not phenotype_order:
        sys.exit("ERROR: No phenotype/simulation blocks were identified.")

    wide_df = make_horizontal(
        long_df,
        phenotype_order,
    )

    print_compact_summary(
        long_df,
        phenotype_order,
        mode,
    )

    outdir = root / "FinalAnalysis02"
    outdir.mkdir(parents=True, exist_ok=True)

    csv_path = (
        outdir
        / f"FinalAnalysis02_{mode}_Horizontal.csv"
    )

    xlsx_path = (
        outdir
        / f"FinalAnalysis02_{mode}_Horizontal.xlsx"
    )

    long_path = (
        outdir
        / f"FinalAnalysis02_{mode}_Long.csv"
    )

    wide_df.to_csv(
        csv_path,
        index=False,
    )

    long_df.round(
        {
            "Original h2": 4,
            "Original SE": 4,
            "Original CI lower": 4,
            "Original CI upper": 4,
            "Liability h2": 4,
            "Liability SE": 4,
            "Liability CI lower": 4,
            "Liability CI upper": 4,
            "Mean variants": 1,
        }
    ).to_csv(
        long_path,
        index=False,
    )

    excel_ok = save_excel(
        wide_df,
        xlsx_path,
        phenotype_order,
    )

    print()
    print("=" * 100)
    print("SAVED")
    print("=" * 100)
    print(f"Mode       : {mode}")
    print(f"Files read : {len(files)}")
    print(f"Blocks     : {len(phenotype_order)}")
    print(f"CSV        : {csv_path}")
    print(f"LONG       : {long_path}")

    if excel_ok:
        print(f"XLSX       : {xlsx_path}")
    else:
        print("XLSX not written. Install xlsxwriter:")
        print("pip install xlsxwriter")


if __name__ == "__main__":
    main()
 
