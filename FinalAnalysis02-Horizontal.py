# AGGREGATE FIVE FOLDS
# =============================================================================

def aggregate_group(g: pd.DataFrame) -> pd.Series:
    original = pd.to_numeric(
        g["h2_original"],
        errors="coerce",
    ).dropna()

    liability = pd.to_numeric(
        g["h2_liability"],
        errors="coerce",
    ).dropna()

    variants = pd.to_numeric(
        g["number_variants"],
        errors="coerce",
    ).dropna()

    mean_original = float(original.mean()) if len(original) else np.nan
    original_se = sem(original)
    original_lo, original_hi = ci95(mean_original, original_se)

    mean_liability = float(liability.mean()) if len(liability) else np.nan
    liability_se = sem(liability)
    liability_lo, liability_hi = ci95(mean_liability, liability_se)

    mean_variants = float(variants.mean()) if len(variants) else np.nan

    return pd.Series(
        {
            "Original h2": mean_original,
            "Original SE": original_se,
            "Original CI lower": original_lo,
            "Original CI upper": original_hi,
            "Original 95% CI": ci_string(original_lo, original_hi),

            "Liability h2": mean_liability,
            "Liability SE": liability_se,
            "Liability CI lower": liability_lo,
            "Liability CI upper": liability_hi,
            "Liability 95% CI": ci_string(liability_lo, liability_hi),

            "Mean variants": mean_variants,
            "Native folds": int(original.notna().sum()),
            "Liability folds": int(liability.notna().sum()),
        }
    )


def make_long(raw: pd.DataFrame) -> pd.DataFrame:
    keys = CONFIG_COLS + ["Phenotype"]

    long_df = (
        raw.groupby(keys, dropna=False, sort=False)
        .apply(
            aggregate_group,
            include_groups=False,
        )
        .reset_index()
    )

    long_df["_method_rank"] = (
        long_df["Method"]
        .map(METHOD_RANK)
        .fillna(999)
    )

    long_df = (
        long_df
        .sort_values(
            [
                "_method_rank",
                "h2model",
                "clumpprune",
                "numberofpca",
                "Phenotype",
            ],
            kind="stable",
        )
        .drop(columns="_method_rank")
        .reset_index(drop=True)
    )

    return long_df


