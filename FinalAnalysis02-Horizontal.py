def clean_config(x):
    if pd.isna(x):
        return "NA"
    s = str(x).strip()
    return s if s else "NA"


def first_col(df: pd.DataFrame, names: list[str]):
    lookup = {str(c).lower(): c for c in df.columns}
    for name in names:
        if name.lower() in lookup:
            return lookup[name.lower()]
    return None


def numeric_col(df: pd.DataFrame, names: list[str]) -> pd.Series:
    col = first_col(df, names)
    if col is None:
        return pd.Series(np.nan, index=df.index, dtype=float)
    return pd.to_numeric(df[col], errors="coerce")


def sem(series: pd.Series) -> float:
    x = pd.to_numeric(series, errors="coerce").dropna()
    if len(x) <= 1:
        return np.nan
    return float(x.std(ddof=1) / np.sqrt(len(x)))


def ci95(mean: float, se: float) -> tuple[float, float]:
    if not np.isfinite(mean) or not np.isfinite(se):
        return np.nan, np.nan
    return mean - 1.96 * se, mean + 1.96 * se


def ci_string(lo: float, hi: float) -> str:
    if not np.isfinite(lo) or not np.isfinite(hi):
        return ""
    return f"[{lo:.4f}, {hi:.4f}]"


def is_sim_id(name: str) -> bool:
    return re.fullmatch(r"Sim\d{3}", str(name)) is not None


def sim_number(name: str) -> int:
    m = re.fullmatch(r"Sim(\d{3})", str(name))
    return int(m.group(1)) if m else 10**9


def rgb_to_hex(rgb) -> str:
    vals = [max(0, min(255, int(round(v * 255)))) for v in rgb]
    return "#{:02X}{:02X}{:02X}".format(*vals)


def pastel_colors(n: int) -> list[str]:
    """
    Generate n distinct LIGHT colors. This works for 10 real phenotypes and
    also for all 200 SimXXX datasets without repeating the same few colors.
    """
    if n <= 0:
        return []

    colors = []
    golden = 0.618033988749895

    for i in range(n):
        hue = (i * golden) % 1.0
        # High value + low/moderate saturation => light/pastel.
        rgb = colorsys.hsv_to_rgb(hue, 0.22, 0.98)
        colors.append(rgb_to_hex(rgb))

    return colors


def darker_pastel(hex_color: str, factor: float = 0.92) -> str:
    h = hex_color.lstrip("#")
    r, g, b = [int(h[i:i+2], 16) for i in (0, 2, 4)]
    r = max(0, min(255, int(r * factor)))
    g = max(0, min(255, int(g * factor)))
    b = max(0, min(255, int(b * factor)))
    return f"#{r:02X}{g:02X}{b:02X}"


