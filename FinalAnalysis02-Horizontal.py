def print_compact_summary(
    long_df: pd.DataFrame,
    phenotype_order: list[str],
    mode: str,
):
    """
    Real: print all 10 phenotype summaries.
    Simulated: print only a concise simulation-coverage check to avoid dumping
    200 huge tables to the terminal.
    """
    if mode == "simulated":
        n_sims = long_df["Phenotype"].nunique()
        n_binary_with_liability = (
            long_df.groupby("Phenotype")["Liability h2"]
            .apply(lambda s: s.notna().any())
            .sum()
        )

        print()
        print("=" * 90)
        print("SIMULATION TABLE CHECK")
        print("=" * 90)
        print(f"Simulations found            : {n_sims}")
        print(f"Simulations with liability h2: {int(n_binary_with_liability)}")
        print(f"Configurations in table      : {long_df[CONFIG_COLS].drop_duplicates().shape[0]}")
        return

    summary = (
        long_df.groupby(
            ["Method", "Phenotype"],
            dropna=False,
        )
        .agg(
            Configurations=("h2model", "size"),
            Original_h2=("Original h2", "mean"),
            Original_SE=("Original SE", "mean"),
            Liability_h2=("Liability h2", "mean"),
            Liability_SE=("Liability SE", "mean"),
            Mean_variants=("Mean variants", "mean"),
        )
        .reset_index()
    )

    summary["_method_rank"] = (
        summary["Method"]
        .map(METHOD_RANK)
        .fillna(999)
    )

    for phenotype in phenotype_order:
        sub = summary[
            summary["Phenotype"] == phenotype
        ].copy()

        if sub.empty:
            continue

        label = PHENOTYPE_LABELS.get(phenotype, phenotype)

        sub = (
            sub
            .sort_values(["_method_rank", "Method"])
            .drop(columns="_method_rank")
        )

        for c in [
            "Original_h2",
            "Original_SE",
            "Liability_h2",
            "Liability_SE",
            "Mean_variants",
        ]:
            sub[c] = pd.to_numeric(sub[c], errors="coerce").round(4)

        print()
        print("=" * 110)
        print(label)
        print("=" * 110)
        print(sub.to_string(index=False, na_rep="NA"))


