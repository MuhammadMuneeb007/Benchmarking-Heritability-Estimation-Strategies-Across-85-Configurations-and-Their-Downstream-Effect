def save_excel(
    df: pd.DataFrame,
    path: Path,
    phenotype_order: list[str],
):
    try:
        import xlsxwriter  # noqa: F401
    except ImportError:
        return False

    colors = pastel_colors(len(phenotype_order))

    with pd.ExcelWriter(
        path,
        engine="xlsxwriter",
    ) as writer:

        workbook = writer.book
        worksheet = workbook.add_worksheet("Heritability")
        writer.sheets["Heritability"] = worksheet

        # -------------------------
        # Formats
        # -------------------------
        config_group_fmt = workbook.add_format(
            {
                "bold": True,
                "font_color": "#FFFFFF",
                "bg_color": "#1F4E78",
                "border": 1,
                "align": "center",
                "valign": "vcenter",
            }
        )

        config_header_fmt = workbook.add_format(
            {
                "bold": True,
                "font_color": "#FFFFFF",
                "bg_color": "#2F75B5",
                "border": 1,
                "align": "center",
                "valign": "vcenter",
                "text_wrap": True,
            }
        )

        config_cell_fmt = workbook.add_format(
            {
                "border": 1,
                "valign": "vcenter",
            }
        )

        # Top-level configuration group.
        worksheet.merge_range(
            0,
            0,
            0,
            3,
            "Configuration",
            config_group_fmt,
        )

        for j, col in enumerate(CONFIG_COLS):
            worksheet.write(1, j, col, config_header_fmt)

        # -------------------------
        # Phenotype group headers
        # -------------------------
        phenotype_formats = {}
        start_col = len(CONFIG_COLS)

        for i, phenotype in enumerate(phenotype_order):
            light = colors[i]
            header_color = darker_pastel(light, 0.91)

            group_fmt = workbook.add_format(
                {
                    "bold": True,
                    "bg_color": header_color,
                    "border": 1,
                    "align": "center",
                    "valign": "vcenter",
                    "font_size": 11,
                }
            )

            subheader_fmt = workbook.add_format(
                {
                    "bold": True,
                    "bg_color": light,
                    "border": 1,
                    "align": "center",
                    "valign": "vcenter",
                    "text_wrap": True,
                }
            )

            numeric_fmt = workbook.add_format(
                {
                    "bg_color": light,
                    "border": 1,
                    "align": "center",
                    "valign": "vcenter",
                    "num_format": "0.0000",
                }
            )

            variants_fmt = workbook.add_format(
                {
                    "bg_color": light,
                    "border": 1,
                    "align": "center",
                    "valign": "vcenter",
                    "num_format": "0.0",
                }
            )

            text_fmt = workbook.add_format(
                {
                    "bg_color": light,
                    "border": 1,
                    "align": "center",
                    "valign": "vcenter",
                }
            )

            phenotype_formats[phenotype] = {
                "numeric": numeric_fmt,
                "variants": variants_fmt,
                "text": text_fmt,
            }

            first = start_col
            last = start_col + len(METRICS) - 1
            label = PHENOTYPE_LABELS.get(phenotype, phenotype)

            worksheet.merge_range(
                0,
                first,
                0,
                last,
                label,
                group_fmt,
            )

            for metric_idx, metric in enumerate(METRICS):
                worksheet.write(
                    1,
                    start_col + metric_idx,
                    metric,
                    subheader_fmt,
                )

            start_col += len(METRICS)

        # -------------------------
        # Data body
        # -------------------------
        for row_idx in range(len(df)):
            excel_row = row_idx + 2

            # Configuration columns
            for col_idx in range(4):
                value = df.iloc[row_idx, col_idx]
                worksheet.write(
                    excel_row,
                    col_idx,
                    "" if pd.isna(value) else value,
                    config_cell_fmt,
                )

            # Phenotype blocks
            col_idx = 4

            for phenotype in phenotype_order:
                formats = phenotype_formats[phenotype]

                for metric in METRICS:
                    flat_col = f"{PHENOTYPE_LABELS.get(phenotype, phenotype)} | {metric}"

                    if flat_col not in df.columns:
                        worksheet.write_blank(
                            excel_row,
                            col_idx,
                            None,
                            formats["text"],
                        )
                        col_idx += 1
                        continue

                    value = df.iloc[row_idx][flat_col]

                    if metric in {"Original 95% CI", "Liability 95% CI"}:
                        worksheet.write(
                            excel_row,
                            col_idx,
                            "" if pd.isna(value) else str(value),
                            formats["text"],
                        )

                    elif metric == "Mean variants":
                        if pd.isna(value):
                            worksheet.write_blank(
                                excel_row,
                                col_idx,
                                None,
                                formats["variants"],
                            )
                        else:
                            worksheet.write_number(
                                excel_row,
                                col_idx,
                                float(value),
                                formats["variants"],
                            )

                    else:
                        if pd.isna(value):
                            worksheet.write_blank(
                                excel_row,
                                col_idx,
                                None,
                                formats["numeric"],
                            )
                        else:
                            worksheet.write_number(
                                excel_row,
                                col_idx,
                                float(value),
                                formats["numeric"],
                            )

                    col_idx += 1

        # -------------------------
        # Layout
        # -------------------------
        worksheet.set_column(0, 0, 30)   # Method
        worksheet.set_column(1, 1, 48)   # h2model
        worksheet.set_column(2, 2, 13)   # clumpprune
        worksheet.set_column(3, 3, 13)   # numberofpca

        # Per-phenotype widths:
        # h2, SE, CI, h2, SE, CI, variants
        widths = [12, 12, 22, 12, 12, 22, 14]

        col_idx = 4
        for _ in phenotype_order:
            for width in widths:
                worksheet.set_column(col_idx, col_idx, width)
                col_idx += 1

        worksheet.set_row(0, 24)
        worksheet.set_row(1, 42)

        worksheet.freeze_panes(2, 4)

        # Auto-filter on the four configuration columns. Repeated phenotype
        # metric names make a single standard Excel Table impractical, but the
        # grid itself is fully bordered and grouped as a proper two-level table.
        worksheet.autofilter(
            1,
            0,
            len(df) + 1,
            3,
        )

        # Light alternating fill only on configuration cells, leaving phenotype
        # blocks visibly colored by phenotype.
        alt_fmt = workbook.add_format({"bg_color": "#F7F7F7"})

        if len(df) > 0:
            worksheet.conditional_format(
                2,
                0,
                len(df) + 1,
                3,
                {
                    "type": "formula",
                    "criteria": "=MOD(ROW(),2)=0",
                    "format": alt_fmt,
                },
            )

        # Add a legend sheet so the phenotype colors are easy to identify,
        # especially for Sim001...Sim200.
        legend = workbook.add_worksheet("Phenotype Colors")
        legend.write(0, 0, "Phenotype / Simulation", config_header_fmt)
        legend.write(0, 1, "Color", config_header_fmt)

        for i, phenotype in enumerate(phenotype_order, start=1):
            light = colors[i - 1]
            fmt = workbook.add_format(
                {
                    "bg_color": light,
                    "border": 1,
                }
            )
            legend.write(
                i,
                0,
                PHENOTYPE_LABELS.get(phenotype, phenotype),
                config_cell_fmt,
            )
            legend.write(i, 1, "", fmt)

        legend.set_column(0, 0, 34)
        legend.set_column(1, 1, 16)
        legend.freeze_panes(1, 0)

    return True


