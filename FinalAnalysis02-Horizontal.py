def load_all(files: list[Path], root: Path, mode: str) -> pd.DataFrame:
    frames = []

    for path in tqdm(
        files,
        desc=f"FinalAnalysis02 ({mode})",
        unit="file",
        dynamic_ncols=True,
        mininterval=0.5,
    ):
        try:
            df = pd.read_csv(path)
        except Exception:
            continue

        if df.empty:
            continue

        try:
            phenotype, fold, method = metadata_from_path(path, root, mode)
        except Exception:
            continue

        h2model_col = first_col(
            df,
            ["h2model", "h2model_standardized", "model"],
        )
        clump_col = first_col(
            df,
            ["clumpprune", "clump_prune"],
        )
        pca_col = first_col(
            df,
            ["numberofpca", "number_of_pca", "pca"],
        )

        out = pd.DataFrame(index=df.index)

        out["Method"] = method
        out["Phenotype"] = phenotype
        out["Fold"] = fold

        out["h2model"] = (
            df[h2model_col].map(clean_config)
            if h2model_col is not None
            else "NA"
        )
        out["clumpprune"] = (
            df[clump_col].map(clean_config)
            if clump_col is not None
            else "NA"
        )
        out["numberofpca"] = (
            df[pca_col].map(clean_config)
            if pca_col is not None
            else "NA"
        )

        # Native/original fold-level result.
        out["h2_original"] = numeric_col(
            df,
            ["h2_native", "h2_observed", "h2"],
        )

        # Liability fold-level result.
        out["h2_liability"] = numeric_col(
            df,
            ["h2_liability_primary", "h2_liability"],
        )

        # Variant count. FinalAnalysis01 normally creates variants_standardized.
        out["number_variants"] = numeric_col(
            df,
            [
                "variants_standardized",
                "numberofvariants",
                "number_of_variants",
                "n_variants",
                "variants",
                "num_variants",
                "n_snps",
                "snps",
            ],
        )

        frames.append(out)

    if not frames:
        return pd.DataFrame()

    return pd.concat(frames, ignore_index=True)


