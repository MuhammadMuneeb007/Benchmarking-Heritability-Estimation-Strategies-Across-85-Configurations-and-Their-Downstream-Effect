def metadata_from_path(path: Path, root: Path, mode: str):
    rel = path.relative_to(root)
    parts = list(rel.parts)

    if mode == "real":
        phenotype = parts[0]
        fold = int(parts[1].split("_")[1])
        method = parts[2]
        return phenotype, fold, method

    sim_id = next((x for x in parts if is_sim_id(x)), None)
    fold_name = next((x for x in parts if re.fullmatch(r"Fold_[0-4]", x)), None)

    if sim_id is None or fold_name is None:
        raise ValueError(f"Invalid simulation result path: {path}")

    fold_idx = parts.index(fold_name)
    fold = int(fold_name.split("_")[1])
    method = parts[fold_idx + 1]

    return sim_id, fold, method


