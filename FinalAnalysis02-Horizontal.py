def make_horizontal(
    long_df: pd.DataFrame,
    phenotype_order: list[str],
) -> pd.DataFrame:

    wide = long_df.pivot(
        index=CONFIG_COLS,
        columns="Phenotype",
        values=METRICS,
    )

    ordered = []

    for phenotype in phenotype_order:
        for metric in METRICS:
            key = (metric, phenotype)
            if key in wide.columns:
                ordered.append(key)

    wide = wide.reindex(
        columns=pd.MultiIndex.from_tuples(ordered)
    )

    wide.columns = [
        f"{PHENOTYPE_LABELS.get(pheno, pheno)} | {metric}"
        for metric, pheno in wide.columns
    ]

    wide = wide.reset_index()

    wide["_method_rank"] = (
        wide["Method"]
        .map(METHOD_RANK)
        .fillna(999)
    )

    wide = (
        wide
        .sort_values(
            [
                "_method_rank",
                "h2model",
                "clumpprune",
                "numberofpca",
            ],
            kind="stable",
        )
        .drop(columns="_method_rank")
        .reset_index(drop=True)
    )

    # Round numeric values, preserve CI strings.
    for col in wide.columns:
        if col in CONFIG_COLS:
            continue
        if col.endswith("95% CI"):
            continue

        numeric = pd.to_numeric(wide[col], errors="coerce")
        if numeric.notna().any():
            if col.endswith("Mean variants"):
                wide[col] = numeric.round(1)
            else:
                wide[col] = numeric.round(4)

    return wide


