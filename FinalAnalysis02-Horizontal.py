def expected_real_files(root: Path) -> list[Path]:
    return [
        root / phenotype / f"Fold_{fold}" / method / "Results_Liability.csv"
        for phenotype in PHENOTYPES
        for fold in FOLDS
        for method in METHODS
    ]


def simulation_directories(root: Path) -> list[Path]:
    """
    Discover production simulations only.

    Supported layouts:
      root/Sim001 ... root/Sim200
      root/simulation/phenotypes/Sim001 ... Sim200
      root/phenotypes/Sim001 ... Sim200

    SampleData1 is deliberately NOT treated as a production simulation.
    """
    candidate_bases = [
        root,
        root / "simulation" / "phenotypes",
        root / "phenotypes",
    ]

    found = {}

    for base in candidate_bases:
        if not base.is_dir():
            continue

        for p in base.iterdir():
            if p.is_dir() and is_sim_id(p.name):
                found[p.name] = p

    return [found[k] for k in sorted(found, key=sim_number)]


def discover_sim_files(root: Path) -> list[Path]:
    files = []

    for sim_dir in simulation_directories(root):
        for fold in FOLDS:
            for method in METHODS:
                p = sim_dir / f"Fold_{fold}" / method / "Results_Liability.csv"
                if p.exists():
                    files.append(p)

    return files


def root_has_simulations(root: Path) -> bool:
    return len(simulation_directories(root)) > 0


def resolve_root(mode: str) -> Path:
    cwd = Path.cwd().resolve()

    if mode == "real":
        env = os.environ.get("HERITABILITY_REAL_ROOT")
        if env:
            p = Path(env).expanduser().resolve()
            if p.exists():
                return p

        if REAL_ROOT.exists():
            return REAL_ROOT.resolve()

        if any((cwd / p).is_dir() for p in PHENOTYPES):
            return cwd

        raise FileNotFoundError("Could not find the real-data project root.")

    # simulated
    env = os.environ.get("HERITABILITY_SIM_ROOT")
    if env:
        p = Path(env).expanduser().resolve()
        if p.exists() and root_has_simulations(p):
            return p

    for candidate in [cwd, SIM_ROOT, REAL_ROOT]:
        try:
            candidate = candidate.resolve()
        except Exception:
            continue

        if candidate.exists() and root_has_simulations(candidate):
            return candidate

    # Last check: likely sibling simulation roots.
    parents = {cwd.parent}
    if REAL_ROOT.exists():
        parents.add(REAL_ROOT.resolve().parent)

    for parent in parents:
        try:
            for candidate in parent.iterdir():
                if candidate.is_dir() and root_has_simulations(candidate):
                    return candidate.resolve()
        except PermissionError:
            pass

    raise FileNotFoundError(
        "Could not locate Sim001...Sim200 Results_Liability.csv files."
    )


