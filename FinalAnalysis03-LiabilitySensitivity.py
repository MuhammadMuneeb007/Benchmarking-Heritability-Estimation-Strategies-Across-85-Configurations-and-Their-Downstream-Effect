def is_sim_id(x: str) -> bool:
    return re.fullmatch(r"Sim\d{3}", str(x)) is not None


def sim_num(x: str) -> int:
    m = re.fullmatch(r"Sim(\d{3})", str(x))
    return int(m.group(1)) if m else 10**9


def first_col(df, names):
    lookup = {str(c).lower(): c for c in df.columns}
    for n in names:
        if n.lower() in lookup:
            return lookup[n.lower()]
    return None


def numcol(df, names):
    c = first_col(df, names)
    if c is None:
        return pd.Series(np.nan, index=df.index, dtype=float)
    return pd.to_numeric(df[c], errors="coerce")


def txtcol(df, names, default=""):
    c = first_col(df, names)
    if c is None:
        return pd.Series(default, index=df.index, dtype=object)
    return df[c].fillna(default).astype(str)


def clean(x):
    if pd.isna(x):
        return "NA"
    s = str(x).strip()
    return s if s else "NA"


def expected_real_files(root):
    return [
        root / ph / f"Fold_{f}" / method / "Results_Liability.csv"
        for ph in PHENOTYPES
        for f in FOLDS
        for method in METHODS
    ]


def simulation_dirs(root):
    bases = [
        root,
        root / "simulation" / "phenotypes",
        root / "phenotypes",
    ]
    found = {}
    for base in bases:
        if not base.is_dir():
            continue
        for p in base.iterdir():
            if p.is_dir() and is_sim_id(p.name):
                found[p.name] = p
    return [found[k] for k in sorted(found, key=sim_num)]


def sim_files(root):
    out = []
    for sim in simulation_dirs(root):
        for f in FOLDS:
            for method in METHODS:
                p = sim / f"Fold_{f}" / method / "Results_Liability.csv"
                if p.exists():
                    out.append(p)
    return out


def resolve_root(mode):
    cwd = Path.cwd().resolve()

    if mode == "real":
        env = os.environ.get("HERITABILITY_REAL_ROOT")
        if env and Path(env).exists():
            return Path(env).resolve()
        if REAL_ROOT.exists():
            return REAL_ROOT.resolve()
        if any((cwd / p).is_dir() for p in PHENOTYPES):
            return cwd
        raise FileNotFoundError("Could not locate real root.")

    env = os.environ.get("HERITABILITY_SIM_ROOT")
    if env and Path(env).exists() and simulation_dirs(Path(env)):
        return Path(env).resolve()

    for p in [cwd, SIM_ROOT, REAL_ROOT]:
        if p.exists() and simulation_dirs(p):
            return p.resolve()

    raise FileNotFoundError("Could not locate Sim001...Sim200.")


def path_meta(path, root, mode):
    rel = path.relative_to(root)
    parts = list(rel.parts)

    if mode == "real":
        return parts[0], int(parts[1].split("_")[1]), parts[2]

    sim = next((p for p in parts if is_sim_id(p)), None)
    fold_name = next((p for p in parts if re.fullmatch(r"Fold_[0-4]", p)), None)
    if sim is None or fold_name is None:
        raise ValueError(path)

    i = parts.index(fold_name)
    return sim, int(fold_name.split("_")[1]), parts[i + 1]


def load_all(files, root, mode):
    frames = []

    for path in tqdm(
        files,
        desc=f"FinalAnalysis03 ({mode})",
        unit="file",
        dynamic_ncols=True,
    ):
        try:
            df = pd.read_csv(path)
        except Exception:
            continue
        if df.empty:
            continue

        try:
            phenotype, fold, method = path_meta(path, root, mode)
        except Exception:
            continue

        h2model = first_col(df, ["h2model", "h2model_standardized", "model"])
        clump = first_col(df, ["clumpprune", "clump_prune"])
        pca = first_col(df, ["numberofpca", "number_of_pca", "pca"])

        x = pd.DataFrame(index=df.index)

        x["Phenotype"] = phenotype
        x["Fold"] = fold
        x["Method"] = method
        x["h2model"] = df[h2model].map(clean) if h2model else "NA"
        x["clumpprune"] = df[clump].map(clean) if clump else "NA"
        x["numberofpca"] = df[pca].map(clean) if pca else "NA"

        x["h2_native"] = numcol(df, ["h2_native", "h2_observed", "h2"])
        x["h2_lowK"] = numcol(df, ["h2_liability_lowK"])
        x["h2_primaryK"] = numcol(df, ["h2_liability_primary", "h2_liability"])
        x["h2_highK"] = numcol(df, ["h2_liability_highK"])

        x["K_low"] = numcol(df, ["K_low"])
        x["K_primary"] = numcol(df, ["K_primary"])
        x["K_high"] = numcol(df, ["K_high"])

        x["P_used"] = numcol(df, ["P_used"])
        x["P_source"] = txtcol(df, ["P_source"])
        x["method_signal_source"] = txtcol(
            df,
            ["method_signal_source"],
        )
        x["conversion_status"] = txtcol(df, ["conversion_status"])

        x["variants"] = numcol(
            df,
            [
                "variants_standardized",
                "numberofvariants",
                "n_variants",
                "variants",
            ],
        )

        frames.append(x)

    if not frames:
        return pd.DataFrame()

    return pd.concat(frames, ignore_index=True)


def mean_or_nan(s):
    x = pd.to_numeric(s, errors="coerce").dropna()
    return float(x.mean()) if len(x) else np.nan


def joined(s):
    vals = sorted(set(str(v) for v in s.dropna() if str(v).strip()))
    return ";".join(vals)


def make_prevalence_audit(raw):
    keys = ["Phenotype", "Method"]

    rows = []
    for key, g in raw.groupby(keys, dropna=False, sort=False):
        phenotype, method = key

        p = pd.to_numeric(g["P_used"], errors="coerce").dropna()

        rows.append(
            {
                "Phenotype": phenotype,
                "Method": method,
                "Signal source": joined(g["method_signal_source"]),
                "P source": joined(g["P_source"]),
                "P mean": float(p.mean()) if len(p) else np.nan,
                "P min": float(p.min()) if len(p) else np.nan,
                "P max": float(p.max()) if len(p) else np.nan,
                "K low": mean_or_nan(g["K_low"]),
                "K primary": mean_or_nan(g["K_primary"]),
                "K high": mean_or_nan(g["K_high"]),
                "Folds": g["Fold"].nunique(),
                "Converted rows": int(
                    g["h2_primaryK"].notna().sum()
                ),
                "Statuses": joined(g["conversion_status"]),
            }
        )

    out = pd.DataFrame(rows)
    out["_mr"] = out["Method"].map(METHOD_RANK).fillna(999)

    if out["Phenotype"].map(is_sim_id).any():
        out["_pr"] = out["Phenotype"].map(sim_num)
    else:
        order = {p: i for i, p in enumerate(PHENOTYPES)}
        out["_pr"] = out["Phenotype"].map(order).fillna(999)

    return (
        out.sort_values(["_pr", "_mr", "Method"])
        .drop(columns=["_pr", "_mr"])
        .reset_index(drop=True)
    )


def make_config_table(raw):
    keys = CONFIG_COLS + ["Phenotype"]

    agg = (
        raw.groupby(keys, dropna=False, sort=False)
        .agg(
            Native_h2=("h2_native", "mean"),
            LowK_h2=("h2_lowK", "mean"),
            PrimaryK_h2=("h2_primaryK", "mean"),
            HighK_h2=("h2_highK", "mean"),
            K_low=("K_low", "mean"),
            K_primary=("K_primary", "mean"),
            K_high=("K_high", "mean"),
            P_mean=("P_used", "mean"),
            Mean_variants=("variants", "mean"),
        )
        .reset_index()
    )

    agg["Delta_low_vs_primary"] = agg["LowK_h2"] - agg["PrimaryK_h2"]
    agg["Delta_high_vs_primary"] = agg["HighK_h2"] - agg["PrimaryK_h2"]

    scenario_values = agg[
        ["LowK_h2", "PrimaryK_h2", "HighK_h2"]
    ]

    agg["Sensitivity_range"] = (
        scenario_values.max(axis=1, skipna=True)
        - scenario_values.min(axis=1, skipna=True)
    )

    denom = agg["PrimaryK_h2"].abs()
    agg["Sensitivity_range_pct"] = np.where(
        denom > 0,
        100.0 * agg["Sensitivity_range"] / denom,
        np.nan,
    )

    # Rank within phenotype; higher h2 gets rank 1.
    for col, label in [
        ("LowK_h2", "Rank_lowK"),
        ("PrimaryK_h2", "Rank_primaryK"),
        ("HighK_h2", "Rank_highK"),
    ]:
        agg[label] = (
            agg.groupby("Phenotype")[col]
            .rank(method="average", ascending=False)
        )

    agg["Rank_shift_low"] = (
        agg["Rank_lowK"] - agg["Rank_primaryK"]
    ).abs()

    agg["Rank_shift_high"] = (
        agg["Rank_highK"] - agg["Rank_primaryK"]
    ).abs()

    agg["Any_rank_change"] = np.where(
        (agg["Rank_shift_low"] > 1e-12)
        | (agg["Rank_shift_high"] > 1e-12),
        "Yes",
        "No",
    )

    agg["_mr"] = agg["Method"].map(METHOD_RANK).fillna(999)

    if agg["Phenotype"].map(is_sim_id).any():
        agg["_pr"] = agg["Phenotype"].map(sim_num)
    else:
        order = {p: i for i, p in enumerate(PHENOTYPES)}
        agg["_pr"] = agg["Phenotype"].map(order).fillna(999)

    agg = (
        agg.sort_values(
            [
                "_pr",
                "_mr",
                "h2model",
                "clumpprune",
                "numberofpca",
            ],
            kind="stable",
        )
        .drop(columns=["_pr", "_mr"])
        .reset_index(drop=True)
    )

    return agg


def make_method_table(config):
    keys = ["Phenotype", "Method"]

    out = (
        config.groupby(keys, dropna=False, sort=False)
        .agg(
            Configurations=("h2model", "size"),
            Native_h2=("Native_h2", "mean"),
            LowK_h2=("LowK_h2", "mean"),
            PrimaryK_h2=("PrimaryK_h2", "mean"),
            HighK_h2=("HighK_h2", "mean"),
            K_low=("K_low", "mean"),
            K_primary=("K_primary", "mean"),
            K_high=("K_high", "mean"),
            P_mean=("P_mean", "mean"),
        )
        .reset_index()
    )

    for col, label in [
        ("LowK_h2", "Rank_lowK"),
        ("PrimaryK_h2", "Rank_primaryK"),
        ("HighK_h2", "Rank_highK"),
    ]:
        out[label] = (
            out.groupby("Phenotype")[col]
            .rank(method="average", ascending=False)
        )

    out["Rank_shift_low"] = (
        out["Rank_lowK"] - out["Rank_primaryK"]
    ).abs()

    out["Rank_shift_high"] = (
        out["Rank_highK"] - out["Rank_primaryK"]
    ).abs()

    out["Method_rank_changed"] = np.where(
        (out["Rank_shift_low"] > 1e-12)
        | (out["Rank_shift_high"] > 1e-12),
        "Yes",
        "No",
    )

    out["_mr"] = out["Method"].map(METHOD_RANK).fillna(999)

    if out["Phenotype"].map(is_sim_id).any():
        out["_pr"] = out["Phenotype"].map(sim_num)
    else:
        order = {p: i for i, p in enumerate(PHENOTYPES)}
        out["_pr"] = out["Phenotype"].map(order).fillna(999)

    return (
        out.sort_values(["_pr", "_mr", "Method"])
        .drop(columns=["_pr", "_mr"])
        .reset_index(drop=True)
    )


def spearman_pair(g, a, b):
    pair = g[[a, b]].dropna()
    if len(pair) < 2:
        return np.nan
    if pair[a].nunique() < 2 or pair[b].nunique() < 2:
        return np.nan
    return float(pair[a].corr(pair[b], method="spearman"))


def make_summary(config, method_table):
    rows = []

    for phenotype, g in config.groupby("Phenotype", sort=False):
        mg = method_table[method_table["Phenotype"] == phenotype]

        valid = g["PrimaryK_h2"].notna()

        rows.append(
            {
                "Phenotype": phenotype,
                "K low": mean_or_nan(g["K_low"]),
                "K primary": mean_or_nan(g["K_primary"]),
                "K high": mean_or_nan(g["K_high"]),
                "Converted configurations": int(valid.sum()),

                "Mean h2 lowK": mean_or_nan(g["LowK_h2"]),
                "Mean h2 primaryK": mean_or_nan(g["PrimaryK_h2"]),
                "Mean h2 highK": mean_or_nan(g["HighK_h2"]),

                "Mean abs delta low-primary": mean_or_nan(
                    (g["LowK_h2"] - g["PrimaryK_h2"]).abs()
                ),
                "Mean abs delta high-primary": mean_or_nan(
                    (g["HighK_h2"] - g["PrimaryK_h2"]).abs()
                ),

                "Median sensitivity range %": float(
                    pd.to_numeric(
                        g["Sensitivity_range_pct"],
                        errors="coerce",
                    ).median()
                ),

                "Max sensitivity range %": float(
                    pd.to_numeric(
                        g["Sensitivity_range_pct"],
                        errors="coerce",
                    ).max()
                ),

                "Spearman native vs primary": spearman_pair(
                    g, "Native_h2", "PrimaryK_h2"
                ),
                "Spearman lowK vs primary": spearman_pair(
                    g, "LowK_h2", "PrimaryK_h2"
                ),
                "Spearman highK vs primary": spearman_pair(
                    g, "HighK_h2", "PrimaryK_h2"
                ),

                "Config ranks changed": int(
                    (g["Any_rank_change"] == "Yes").sum()
                ),

                "Method ranks changed": int(
                    (mg["Method_rank_changed"] == "Yes").sum()
                ),

                "Maximum method rank shift": float(
                    pd.concat(
                        [
                            mg["Rank_shift_low"],
                            mg["Rank_shift_high"],
                        ]
                    ).max()
                )
                if not mg.empty
                else np.nan,
            }
        )

    out = pd.DataFrame(rows)

    if out["Phenotype"].map(is_sim_id).any():
        out["_order"] = out["Phenotype"].map(sim_num)
    else:
        order = {p: i for i, p in enumerate(PHENOTYPES)}
        out["_order"] = out["Phenotype"].map(order).fillna(999)

    return (
        out.sort_values("_order")
        .drop(columns="_order")
        .reset_index(drop=True)
    )


def pastel(n):
    colors = []
    phi = 0.618033988749895
    for i in range(max(1, n)):
        h = (i * phi) % 1.0
        r, g, b = colorsys.hsv_to_rgb(h, 0.20, 0.98)
        colors.append(
            "#{:02X}{:02X}{:02X}".format(
                int(r * 255),
                int(g * 255),
                int(b * 255),
            )
        )
    return colors


def save_excel(path, summary, audit, method, config):
    try:
        import xlsxwriter  # noqa
    except ImportError:
        return False

    with pd.ExcelWriter(path, engine="xlsxwriter") as writer:
        sheets = {
            "Summary": summary,
            "Prevalence Audit": audit,
            "Method Sensitivity": method,
            "Configuration Sensitivity": config,
        }

        for sheet, df in sheets.items():
            df.to_excel(writer, sheet_name=sheet, index=False)
            ws = writer.sheets[sheet]
            wb = writer.book

            header = wb.add_format(
                {
                    "bold": True,
                    "bg_color": "#D9EAF7",
                    "border": 1,
                    "text_wrap": True,
                    "align": "center",
                    "valign": "vcenter",
                }
            )

            for j, col in enumerate(df.columns):
                ws.write(0, j, col, header)
                width = min(
                    max(
                        len(str(col)) + 2,
                        int(
                            min(
                                40,
                                max(
                                    [len(str(col))]
                                    + [
                                        len(str(v))
                                        for v in df[col].head(200).fillna("")
                                    ]
                                ),
                            )
                        )
                        + 2,
                    ),
                    44,
                )
                ws.set_column(j, j, width)

            ws.freeze_panes(1, 2)
            ws.autofilter(
                0,
                0,
                max(0, len(df)),
                max(0, len(df.columns) - 1),
            )

    return True


def print_table(title, df):
    print()
    print("=" * 140)
    print(title)
    print("=" * 140)

    with pd.option_context(
        "display.max_rows", None,
        "display.max_columns", None,
        "display.width", 300,
        "display.max_colwidth", 60,
    ):
        print(df.to_string(index=False, na_rep="NA"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "mode",
        nargs="?",
        default="real",
        choices=["real", "simulated"],
    )
    args = parser.parse_args()

    mode = args.mode

    try:
        root = resolve_root(mode)
    except FileNotFoundError as exc:
        sys.exit(f"ERROR: {exc}")

    if mode == "real":
        files = [p for p in expected_real_files(root) if p.exists()]
    else:
        files = sim_files(root)

    if not files:
        sys.exit("ERROR: No Results_Liability.csv files found.")

    raw = load_all(files, root, mode)

    if raw.empty:
        sys.exit("ERROR: No usable rows loaded.")

    audit = make_prevalence_audit(raw)
    config = make_config_table(raw)
    method = make_method_table(config)
    summary = make_summary(config, method)

    # Round display / exported numeric values.
    for df in [audit, config, method, summary]:
        for col in df.columns:
            if pd.api.types.is_numeric_dtype(df[col]):
                if "variants" in col.lower():
                    df[col] = df[col].round(1)
                else:
                    df[col] = df[col].round(6)

    # Print EVERYTHING requested.
    print_table(
        "1. PREVALENCE / CONVERSION AUDIT — WHICH P AND K WERE USED",
        audit,
    )
    print_table(
        "2. K-SENSITIVITY SUMMARY BY PHENOTYPE / SIMULATION",
        summary,
    )
    print_table(
        "3. METHOD-LEVEL K-SENSITIVITY AND RANK CHECK",
        method,
    )
    print_table(
        "4. CONFIGURATION-LEVEL K-SENSITIVITY — FULL TABLE",
        config,
    )

    outdir = root / "FinalAnalysis03"
    outdir.mkdir(parents=True, exist_ok=True)

    p_audit = outdir / f"FinalAnalysis03_{mode}_PrevalenceAudit.csv"
    p_summary = outdir / f"FinalAnalysis03_{mode}_K_Sensitivity_Summary.csv"
    p_method = outdir / f"FinalAnalysis03_{mode}_K_Sensitivity_Method.csv"
    p_config = outdir / f"FinalAnalysis03_{mode}_K_Sensitivity_Config.csv"
    p_xlsx = outdir / f"FinalAnalysis03_{mode}_K_Sensitivity.xlsx"

    audit.to_csv(p_audit, index=False)
    summary.to_csv(p_summary, index=False)
    method.to_csv(p_method, index=False)
    config.to_csv(p_config, index=False)

    excel_ok = save_excel(
        p_xlsx,
        summary,
        audit,
        method,
        config,
    )

    print()
    print("=" * 140)
    print("SAVED")
    print("=" * 140)
    print(f"AUDIT   : {p_audit}")
    print(f"SUMMARY : {p_summary}")
    print(f"METHOD  : {p_method}")
    print(f"CONFIG  : {p_config}")
    if excel_ok:
        print(f"XLSX    : {p_xlsx}")
    else:
        print("XLSX not written; install xlsxwriter: pip install xlsxwriter")


if __name__ == "__main__":
    main()
