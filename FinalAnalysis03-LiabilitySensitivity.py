#!/usr/bin/env python3
"""
FinalAnalysis03-LiabilitySensitivity.py

Usage
-----
python FinalAnalysis03-LiabilitySensitivity.py
python FinalAnalysis03-LiabilitySensitivity.py real
python FinalAnalysis03-LiabilitySensitivity.py simulated

Default: real

Purpose
-------
Quantify sensitivity of liability-scale h2 to K_low / K_primary / K_high.

Reads fold-level Results_Liability.csv generated by FinalAnalysis01.

Outputs
-------
FinalAnalysis03/
  FinalAnalysis03_<mode>_PrevalenceAudit.csv
  FinalAnalysis03_<mode>_K_Sensitivity_Config.csv
  FinalAnalysis03_<mode>_K_Sensitivity_Method.csv
  FinalAnalysis03_<mode>_K_Sensitivity_Summary.csv
  FinalAnalysis03_<mode>_K_Sensitivity.xlsx

The script prints ALL sensitivity tables to the terminal.

Important
---------
For a fixed phenotype, changing K multiplies every eligible estimate by the
same positive K-dependent factor relative to K_primary. Therefore, when the
same K is applied to all methods for that phenotype, within-phenotype rank
ordering should remain unchanged apart from missing values/ties/numerical
rounding. This script explicitly checks that.
"""

